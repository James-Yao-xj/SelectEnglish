import Foundation

func check(_ condition: @autoclosure () -> Bool, _ message: String) { precondition(condition(), message) }
var state = PopupDismissalState()
check(!state.shouldDismissMouseDown(timestamp: 10, popupVisible: false, pointInsidePopup: false), "idle hidden clicks do nothing")
state.beginCapture(generation: 1, startedAt: 100)
check(state.hasPendingCapture, "pending capture exists before popup")
check(!state.shouldDismissMouseDown(timestamp: 99, popupVisible: false, pointInsidePopup: false), "delayed initiating mouse-down is ignored")
check(!state.shouldDismissMouseDown(timestamp: 100, popupVisible: true, pointInsidePopup: false), "equal timestamp cannot cancel its own trigger")
check(state.shouldDismissMouseDown(timestamp: 101, popupVisible: false, pointInsidePopup: true), "later local click cancels even hidden pending capture")
check(state.shouldDismissMouseDown(timestamp: 101, popupVisible: false, pointInsidePopup: false), "later global click cancels hidden pending capture")
state.invalidateCapture()
check(!state.completeCapture(generation: 1), "dismissed AX completion cannot be accepted")
check(!state.hasPendingCapture, "invalidation clears pending state")
state.beginCapture(generation: 2, startedAt: 200)
state.beginCapture(generation: 3, startedAt: 300)
check(!state.completeCapture(generation: 2) && state.hasPendingCapture, "old AX callback cannot clear newer pending capture")
check(!state.shouldDismissMouseDown(timestamp: 250, popupVisible: false, pointInsidePopup: false), "old mouse event cannot dismiss newer capture")
check(state.completeCapture(generation: 3) && !state.hasPendingCapture, "current completion clears before show")
check(!state.shouldDismissMouseDown(timestamp: 299, popupVisible: true, pointInsidePopup: false), "initiating mouse-down still ignored after fast AX completion shows popup")
state.invalidateCapture()
check(!state.shouldDismissMouseDown(timestamp: 300, popupVisible: true, pointInsidePopup: false), "AI-start invalidation retains initiating event cutoff")
check(!state.shouldDismissMouseDown(timestamp: 301, popupVisible: true, pointInsidePopup: true), "inside visible popup remains open")
check(state.shouldDismissMouseDown(timestamp: 301, popupVisible: true, pointInsidePopup: false), "outside visible popup closes")
check(!state.shouldDismissMouseDown(timestamp: 302, popupVisible: false, pointInsidePopup: false), "hidden completed popup ignores idle clicks")
print("Popup dismissal: pending, event-order, supersession and visible/idle checks passed")
